def build_document():
    doc = Document()
    setup_styles(doc)
    for s in doc.sections:
        s.top_margin = Cm(2)
        s.bottom_margin = Cm(2)
        s.left_margin = Cm(2.5)
        s.right_margin = Cm(1.5)

    build_title(doc)
    doc.add_page_break()
    build_discussion(doc)
    build_theory(doc)
    doc.add_page_break()
    build_diagrams(doc)
    doc.add_page_break()
    build_example(doc)
    doc.add_page_break()
    build_level1(doc)
    doc.add_page_break()
    build_level2(doc)
    doc.add_page_break()
    build_level3(doc)
    doc.add_page_break()
    build_control_questions(doc)
    doc.add_page_break()
    build_evaluation(doc)
    build_glossary(doc)
    return doc


