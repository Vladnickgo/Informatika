def encode_plantuml(text):
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = compressor.compress(text.encode("utf-8")) + compressor.flush()
    alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"
    result = ""
    for i in range(0, len(data), 3):
        chunk = data[i:i + 3]
        if len(chunk) == 3:
            b1, b2, b3 = chunk
            result += alphabet[b1 >> 2]
            result += alphabet[((b1 & 0x3) << 4) | (b2 >> 4)]
            result += alphabet[((b2 & 0xF) << 2) | (b3 >> 6)]
            result += alphabet[b3 & 0x3F]
        elif len(chunk) == 2:
            b1, b2 = chunk
            result += alphabet[b1 >> 2]
            result += alphabet[((b1 & 0x3) << 4) | (b2 >> 4)]
            result += alphabet[(b2 & 0xF) << 2]
        elif len(chunk) == 1:
            b1 = chunk[0]
            result += alphabet[b1 >> 2]
            result += alphabet[(b1 & 0x3) << 4]
    return result


def download_plantuml(source, path):
    encoded = encode_plantuml(source)
    url = f"https://www.plantuml.com/plantuml/png/{encoded}"
    try:
        log.info(f"  ↳ {os.path.basename(path)}")
        r = requests.get(url, timeout=30)
        r.raise_for_status()
        if not r.content.startswith(b"\x89PNG"):
            log.error("  ↳ отримано не PNG")
            return False
        with open(path, "wb") as f:
            f.write(r.content)
        return True
    except Exception as e:
        log.error(f"  ↳ помилка: {e}")
        return False


